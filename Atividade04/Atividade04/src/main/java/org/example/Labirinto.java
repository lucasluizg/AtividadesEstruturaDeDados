    public static boolean retrocesso() {

        while (!pilha.isEmpty()) {
            int linha = pilha.peek().linha;
            int coluna = pilha.peek().coluna;

            if (mapa[linha][coluna] == 'T') {
                return true;
            } else if (linha - 1 >= 0) {
                if (mapa[linha - 1][coluna] == ' ' ) {
                    mapa[linha - 1][coluna] = '+';
                    Posicao p = new Posicao(linha - 1, coluna);
                    pilha.push(p);
                    continue;
                } else if (mapa[linha - 1][coluna] == 'T'){
                    Posicao p = new Posicao(linha - 1, coluna);
                    pilha.push(p);
                    continue;
                }
            }
            if (coluna - 1 >= 0) {
                if (mapa[linha][coluna - 1] == ' ') {
                    mapa[linha][coluna - 1] = '+';
                    Posicao p = new Posicao(linha, coluna - 1);
                    pilha.push(p);
                    continue;
                } else if (mapa[linha][coluna - 1] == 'T') {
                    Posicao p = new Posicao(linha, coluna - 1);
                    pilha.push(p);
                    continue;
                }
            }
            if (coluna + 1 <= mapa[linha].length - 1) {
                if (mapa[linha][coluna + 1] == ' ' ) {
                    mapa[linha][coluna + 1] = '+';
                    Posicao p = new Posicao(linha, coluna + 1);
                    pilha.push(p);
                    continue;
                } else if (mapa[linha][coluna + 1] == 'T') {
                    Posicao p = new Posicao(linha, coluna + 1);
                    pilha.push(p);
                    continue;
                }
            }
            if (linha + 1 <= mapa.length - 1) {
                if (mapa[linha + 1][coluna] == ' ') {
                    mapa[linha + 1][coluna] = '+';
                    Posicao p = new Posicao(linha + 1, coluna);
                    pilha.push(p);
                    continue;
                } else if (mapa[linha + 1][coluna] == 'T') {
                    Posicao p = new Posicao(linha + 1, coluna);
                    pilha.push(p);
                    continue;
                }
            }
            pilha.pop();
        }
        return false;
    }

